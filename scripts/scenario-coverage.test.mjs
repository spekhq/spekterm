/** change 的所在 —— 封存後它會搬到 `archive/` 之下，兩處都找。 */
function specRoots() {
  const changes = join(repoRoot, 'openspec', 'changes')
  const archived = readdirSync(join(changes, 'archive'), { withFileTypes: true }).filter((entry) =>
    entry.isDirectory(),
  )
  const candidates = COVERED_CHANGES.flatMap((name) => [
    join(changes, name, 'specs'),
    ...archived
      .filter((entry) => entry.name.endsWith(name))
      .map((entry) => join(changes, 'archive', entry.name, 'specs')),
  ])
  return candidates.filter((dir) => {
    try {
      readdirSync(dir)
      return true
    } catch {
      return false
    }
  })
}

export function scenariosOf(root) {
  const found = []
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name)
      if (entry.isDirectory()) walk(full)
      else if (entry.name === 'spec.md') {
        for (const line of readFileSync(full, 'utf8').split('\n')) {
          if (line.startsWith('#### Scenario:')) found.push(line.slice('#### Scenario:'.length).trim())
        }
      }
    }
  }
  walk(root)
  return found
}

